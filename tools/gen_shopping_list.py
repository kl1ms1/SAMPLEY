def links(q):
    return " · ".join(f"[{n}]({u.format(quote_plus(q))})" for n, u in SHOPS)


def main():
    out = ["# SAMPLEY — список покупок", "",
           "> Файл сгенерирован `tools/gen_shopping_list.py` — правь список там.", "",
           "Ссылки ведут на **поиск** по маркетплейсу, а не на конкретного продавца:",
           "цены и наличие меняются каждый день. Выбирай карточку с отзывами и сверяй",
           "колонку «Проверить».", "",
           "**🟢 — купить и поставить самому, 🔵 — мелкая микросхема: её ставит завод при заказе платы.**", ""]
    for title, items in SECTIONS:
        out += ["", f"## {title}", "", "| | Что | Шт. | Проверить | Где искать |", "|---|---|---|---|---|"]
        for icon, what, q, n, check in items:
            out.append(f"| {icon} | {what}<br>`{q}` | {n} | {check or '—'} | {links(q)} |")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"→ {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
